def backdrop(theme, w=1280, h=720, darken=1.0):
    sky = Image.open(out("assets", "backgrounds", theme, "sky.png"))
    far = Image.open(out("assets", "backgrounds", theme, "far.png"))
    mid = Image.open(out("assets", "backgrounds", theme, "mid.png"))
    img = sky.crop((0, 0, w, h)).copy()
    img.alpha_composite(far.crop((0, 1024 - h - 80, w, 1024 - 80)))
    img.alpha_composite(mid.crop((200, 1024 - h, 200 + w, 1024)))
    if darken != 1.0:
        img = ImageEnhance.Brightness(img).enhance(darken)
    return img


def vignette(img, strength=0.55):
    w, h = img.size
    mask = Image.radial_gradient("L").resize((w, h))       # 0 at centre -> 255 at corners
    mask = mask.point(lambda v: int(max(0, v - 90) * strength * 1.6))
    black = Image.new("RGBA", (w, h), (0, 0, 0, 255))
    black.putalpha(mask)
    img.alpha_composite(black)
    return img


def roof(img, y, color="#2a2738"):
    d = ImageDraw.Draw(img)
    d.rectangle((0, y, img.width, img.height), fill=hexc(color))
    d.rectangle((0, y, img.width, y + 10), fill=hexc("#4a4660"))


def place(img, sprite, cx, base_y):
    img.alpha_composite(sprite, (int(cx - sprite.width / 2), int(base_y - sprite.height)))


def explosion(img, c, r):
    glow = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(glow)
    for k, col in enumerate(("#ff5a1c", "#ffa23a", "#ffe08a", "#ffffff")):
        rr = r * (1 - k * 0.22)
        d.ellipse((c[0] - rr, c[1] - rr, c[0] + rr, c[1] + rr), fill=hexc(col)[:3] + (230,))
    glow = glow.filter(ImageFilter.GaussianBlur(6))
    img.alpha_composite(glow)


